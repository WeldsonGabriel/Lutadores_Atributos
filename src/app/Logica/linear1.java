package app.Logica;

public class linear1 {
    public static void main(String[] args) {
        // execicio de logica linear
        int a = 5;
        int b = 10;
        int c = a + b;
        System.out.println("O resultado de " + a + " + " + b + " é: " + c);

        int mult = 2;
        int mult1 = 5;
        int resultado = mult * mult1;
        System.out.println("O resultado de " + mult + " * " + mult1 + " é: " + resultado);
    }
}
