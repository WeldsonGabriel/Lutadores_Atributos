package app.Logica;

public class CAsting {
    public static void main(String[] args) {
        double inteiro = (int) 100.45; // Cast de float para int
        int numeroInteiro = 10;
        String numeroString = Integer.toString(numeroInteiro);
        System.out.println("Valor inteiro: " + inteiro);
        System.out.println("Número como String: " + numeroString);
    }
}

